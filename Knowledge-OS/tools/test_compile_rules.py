"""
Knowledge-OS Rule Compiler — 静态验证测试套件

运行方式：
    python tools/test_compile_rules.py

注意：Windows sandbox 禁止 subprocess.PIPE，本测试读取已编译的生成文件做静态验证。
运行前请确保最后一次编译已成功执行（python tools/compile_rules.py）。
"""

import sys
import json
import re
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parents[2]
GENERATED_DIR = BASE_DIR / "Knowledge-OS" / "07-Agent-Rules" / "generated"
MANIFEST_PATH = GENERATED_DIR / ".manifest.json"

PASS = 0
FAIL = 0

def test(name, condition, detail=""):
    global PASS, FAIL
    if condition:
        PASS += 1
        print(f"  [PASS] {name}")
    else:
        FAIL += 1
        print(f"  [FAIL] {name}  —  {detail}")

def run():
    global PASS, FAIL

    print("=" * 60)
    print("  Knowledge-OS Rule Compiler — 静态验证测试套件")
    print("=" * 60)

    # 1. Manifest 存在且有效
    print("\n[1] Manifest 验证")
    if not MANIFEST_PATH.exists():
        test("manifest 文件存在", False, f"{MANIFEST_PATH} 不存在")
        print("\n  请先运行: python tools/compile_rules.py\n")
        return 1

    manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    test("manifest 包含 generated_files 列表", "generated_files" in manifest)
    test("manifest 包含 total_rules 字段", "total_rules" in manifest)
    test("total_rules > 0", manifest.get("total_rules", 0) > 0,
         f"实际值: {manifest.get('total_rules')}")
    test("generated_files 非空", len(manifest.get("generated_files", [])) > 0)

    # 2. 每个 generated_file 实际存在且有内容
    print("\n[2] 生成文件完整性")
    for fname in manifest["generated_files"]:
        fpath = GENERATED_DIR / fname
        if not fpath.exists():
            test(f"{fname} 文件存在", False)
            continue
        test(f"{fname} 文件存在", True)
        size = len(fpath.read_text(encoding="utf-8"))
        test(f"{fname} 非空 (size={size})", size > 50, f"size={size}")

    # 3. 每条规则解析
    print("\n[3] 规则内容验证")
    all_ids = set()
    duplicates = []
    rule_count = 0

    for fname in manifest["generated_files"]:
        fpath = GENERATED_DIR / fname
        if not fpath.exists():
            continue
        content = fpath.read_text(encoding="utf-8")
        for line in content.splitlines():
            m = re.match(
                r"^- \[([\w-]+)\] \[([\w-]+)\] \[([\w-]+)\] (.+?) \(Source: ([^)]+)\)$",
                line
            )
            if not m:
                continue
            rule_count += 1
            rid, enf, ovr, txt = m.group(1), m.group(2), m.group(3), m.group(4)

            if rid in all_ids:
                duplicates.append(rid)
            all_ids.add(rid)

    test("总规则数 = manifest 声明数",
         rule_count == manifest["total_rules"],
         f"实际={rule_count}, 声明={manifest['total_rules']}")
    test("无重复 rule_id", len(duplicates) == 0,
         f"重复: {duplicates}")

    # 4. 基本格式规范
    print("\n[4] 格式规范检查")
    for fname in manifest["generated_files"]:
        fpath = GENERATED_DIR / fname
        if not fpath.exists():
            continue
        content = fpath.read_text(encoding="utf-8")
        test(f"{fname} 包含 HEADER 注释",
             "AUTOMATICALLY GENERATED BY tools/compile_rules.py" in content)
        test(f"{fname} 包含 'Compiled Domain Rules:' 标题",
             "Compiled Domain Rules:" in content)

    # 5. 所有域是否已覆盖
    print("\n[5] 域覆盖度")
    expected_domains = {"requirements", "engineering-assets", "seo-geo",
                        "cro-marketing", "operations"}
    actual_domains = set()
    for fname in manifest["generated_files"]:
        # 文件名格式: {domain}-rules.md
        domain_part = fname.replace("-rules.md", "")
        actual_domains.add(domain_part)
    missing = expected_domains - actual_domains
    extra = actual_domains - expected_domains
    test("所有预期域均已覆盖", len(missing) == 0,
         f"缺失: {missing}")
    if extra:
        test(f"额外域: {extra}", True)

    # 6. 机器可读规则索引 (rules.json)
    print("\n[6] 机器可读规则索引 (rules.json)")
    rules_json_path = GENERATED_DIR / "rules.json"
    test("rules.json 存在", rules_json_path.exists(), str(rules_json_path))
    if rules_json_path.exists():
        try:
            payload = json.loads(rules_json_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            test("rules.json 可解析", False, str(exc))
        else:
            test("rules.json 可解析", True)
            test("schema_version = 1", payload.get("schema_version") == 1,
                 f"实际: {payload.get('schema_version')}")
            test("rules.json 规则数 = manifest 声明数",
                 len(payload.get("rules", [])) == manifest["total_rules"],
                 f"实际={len(payload.get('rules', []))}, 声明={manifest['total_rules']}")
            test("rules.json 覆盖全部规则 ID",
                 {rule.get("id") for rule in payload.get("rules", [])} == all_ids,
                 "与生成文件解析出的 ID 集合不一致")
            test("rules.json 域数量 = 规则文件数",
                 len(payload.get("domains", [])) == len(manifest["generated_files"]),
                 f"实际={len(payload.get('domains', []))}")
            required = ("id", "domain", "priority", "enforcement",
                        "overridable", "rule", "check", "source")
            incomplete = [
                rule.get("id") for rule in payload.get("rules", [])
                if not all(key in rule for key in required)
            ]
            test("每条规则含看板所需字段", not incomplete, f"缺失: {incomplete[:3]}")

    # 7. 统计汇总
    print("\n" + "=" * 60)
    print(f"  测试结果: {PASS} 通过, {FAIL} 失败 / {PASS + FAIL} 总计")
    print("=" * 60)
    return 0 if FAIL == 0 else 1

if __name__ == "__main__":
    sys.exit(run())
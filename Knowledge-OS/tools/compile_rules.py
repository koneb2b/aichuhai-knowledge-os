#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
compile_rules.py — 把 SOP frontmatter 的 agent_rules 编译成 Agent 可消费的规则产物

产物（全部为生成物，禁止手改）:
  1. Knowledge-OS/07-Agent-Rules/generated/{domain}-rules.md   opencode.json 载入
  2. Knowledge-OS/07-Agent-Rules/generated/.manifest.json       计数与文件清单
  3. .cursorrules                                               Cursor 入口，含全部规则 ID

校验策略: fail-closed。必填字段缺失 / 类型错误 / 枚举越界 / 域不在白名单 /
ID 格式非法 / 规则 ID 重复 → 退出码 1，且不写入任何文件。
未知字段只告警（拼写错误仍会因必填字段缺失而失败，但不会阻断字段演进）。

用法:
  python Knowledge-OS/tools/compile_rules.py            # 校验并写入
  python Knowledge-OS/tools/compile_rules.py --dry-run  # 只校验，不写
"""

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

import yaml

BASE_DIR = Path(__file__).resolve().parents[2]
KB_DIR = BASE_DIR / "Knowledge-OS"
GENERATED_DIR = KB_DIR / "07-Agent-Rules" / "generated"
MANIFEST_PATH = GENERATED_DIR / ".manifest.json"
CURSORRULES_PATH = BASE_DIR / ".cursorrules"

HEADER_COMMENT = """# =================================================================
# THIS FILE IS AUTOMATICALLY GENERATED BY tools/compile_rules.py
# DO NOT EDIT THIS FILE DIRECTLY. EDIT SOURCE SOPs IN Knowledge-OS/
# =================================================================
"""

CURSOR_HEADER = """# =================================================================
# THIS FILE IS AUTOMATICALLY GENERATED BY Knowledge-OS/tools/compile_rules.py
# DO NOT EDIT THIS FILE DIRECTLY. EDIT SOURCE SOPs IN Knowledge-OS/
# 自检: python Knowledge-OS/tools/check_rules.py
# =================================================================
"""

# 域白名单。新增域必须在此登记，否则编译失败——避免 domain 拼错被静默降级。
DOMAIN_TITLES = {
    "requirements": "选品与需求 (Requirements)",
    "engineering-assets": "工程安全 (Engineering Assets)",
    "seo-geo": "SEO & GEO 收录 (SEO Standard)",
    "cro-marketing": "CRO 与分发 (Distribution & CRO)",
    "operations": "运营与合规 (Operations)",
}

ENFORCEMENTS = ("block", "must", "should", "may")
RULE_FIELDS = ("id", "rule", "priority", "enforcement", "overridable")
OPTIONAL_FIELDS = ("check",)
CHECK_TYPES = ("grep", "ast", "file", "config", "manual")
RULE_ID_RE = re.compile(r"^[A-Z]{2,10}-\d{3}-[A-Z]$")
FRONTMATTER_RE = re.compile(r"^---\s*\n(.*?)\n---", re.DOTALL)
LAST_UPDATED_RE = re.compile(r'^last_updated:\s*"?(\d{4}-\d{2}-\d{2})"?\s*$', re.MULTILINE)


def collect_rules():
    """扫描全部 SOP，返回 (rules_by_domain, errors, warnings, stamp)。不写任何文件。"""
    rules_by_domain = {}
    errors = []
    warnings = []
    seen = {}
    stamps = []

    for path in sorted(KB_DIR.rglob("*.md")):
        if "07-Agent-Rules" in path.parts or path.name == "Dashboard.md":
            continue

        text = path.read_text(encoding="utf-8")
        front = FRONTMATTER_RE.search(text)
        if not front:
            continue

        found = LAST_UPDATED_RE.search(front.group(1))
        if found:
            stamps.append(found.group(1))

        try:
            data = yaml.safe_load(front.group(1))
        except yaml.YAMLError as exc:
            errors.append(f"[{path.name}] frontmatter YAML 解析失败: {exc}")
            continue

        if not isinstance(data, dict) or not isinstance(data.get("agent_rules"), list):
            continue

        name = path.name
        domain = data.get("domain")
        doc_id = data.get("id")
        version = data.get("version")

        if not isinstance(domain, str) or not domain.strip():
            errors.append(f"[{name}] 缺少必填字段 domain")
            continue
        domain = domain.strip().lower()
        if domain not in DOMAIN_TITLES:
            errors.append(
                f"[{name}] 非法 domain '{domain}'（允许: {', '.join(DOMAIN_TITLES)}）"
            )
            continue
        if not isinstance(doc_id, str) or not doc_id.strip():
            errors.append(f"[{name}] 缺少必填字段 id")
            continue
        if not version:
            errors.append(f"[{name}] 缺少必填字段 version")
            continue

        for idx, item in enumerate(data["agent_rules"], 1):
            where = f"[{name} #{idx}]"
            if not isinstance(item, dict):
                errors.append(f"{where} agent_rules 条目必须是映射(dict)")
                continue

            rid = item.get("id")
            if not isinstance(rid, str) or not rid.strip():
                errors.append(f"{where} 缺少必填字段 id")
                continue
            rid = rid.strip()
            where = f"[{name} {rid}]"

            if not RULE_ID_RE.match(rid):
                errors.append(f"{where} id 不符合 <域缩写>-<3位数字>-<字母> 格式")

            missing = [key for key in RULE_FIELDS if key not in item]
            if missing:
                errors.append(f"{where} 缺少必填字段: {', '.join(missing)}")
                continue

            unknown = [str(key) for key in item if key not in RULE_FIELDS + OPTIONAL_FIELDS]
            if unknown:
                warnings.append(f"{where} 未知字段被忽略: {', '.join(unknown)}")

            rule_text = item["rule"]
            if not isinstance(rule_text, str) or not rule_text.strip():
                errors.append(f"{where} rule 必须是非空字符串")
                continue

            priority = item["priority"]
            if isinstance(priority, bool) or not isinstance(priority, int) or not 0 <= priority <= 100:
                errors.append(f"{where} priority 必须是 0-100 的整数，实际: {priority!r}")
                continue

            enforcement = item["enforcement"]
            if not isinstance(enforcement, str) or enforcement.strip().lower() not in ENFORCEMENTS:
                errors.append(
                    f"{where} enforcement 必须是 {'/'.join(ENFORCEMENTS)} 之一，实际: {enforcement!r}"
                )
                continue
            enforcement = enforcement.strip().lower()

            overridable = item["overridable"]
            if not isinstance(overridable, bool):
                errors.append(f"{where} overridable 必须是布尔值，实际: {overridable!r}")
                continue

            check = item.get("check")
            if check is not None:
                if not isinstance(check, dict) or check.get("type") not in CHECK_TYPES:
                    errors.append(f"{where} check.type 必须是 {'/'.join(CHECK_TYPES)} 之一")
                    continue
                if check["type"] != "manual":
                    for key in ("target", "assertion"):
                        value = check.get(key)
                        if not isinstance(value, str) or not value.strip():
                            errors.append(
                                f"{where} check.type={check['type']} 时 check.{key} 必填"
                            )

            if rid in seen:
                errors.append(f"{where} 重复规则 ID（已定义于 {seen[rid]}）")
                continue
            seen[rid] = name

            rules_by_domain.setdefault(domain, []).append({
                "id": rid,
                "doc_id": doc_id.strip(),
                "version": str(version),
                "priority": priority,
                "enforcement": enforcement,
                "overridable": overridable,
                "rule": rule_text.strip(),
            })

    stamp = max(stamps) if stamps else "unknown"
    return rules_by_domain, errors, warnings, stamp


def sorted_rules(rules):
    """priority 降序，同优先级按 ID 升序（确定性输出）。"""
    return sorted(rules, key=lambda item: (-item["priority"], item["id"]))


def render_domain_file(domain, rules):
    body = []
    for rule in sorted_rules(rules):
        override_tag = "NON-OVERRIDABLE" if not rule["overridable"] else "OVERRIDABLE"
        body.append(
            f"- [{rule['id']}] [{rule['enforcement'].upper()}] [{override_tag}] "
            f"{rule['rule']} (Source: {rule['doc_id']}@v{rule['version']})\n"
        )
    return (
        HEADER_COMMENT
        + "\n"
        + f"# Compiled Domain Rules: {domain.upper()}\n\n"
        + "".join(body)
    )


def render_manifest(rules_by_domain):
    return json.dumps(
        {
            "generated_files": [f"{domain}-rules.md" for domain in rules_by_domain],
            "total_rules": sum(len(rules) for rules in rules_by_domain.values()),
        },
        indent=2,
    )


def render_cursorrules(rules_by_domain, total, stamp):
    lines = [CURSOR_HEADER]
    lines.append("# AI 产品出海开发与工程风控规则 (.cursorrules)\n")
    lines.append(f"# 生效规则数: {total} ({stamp})\n")
    lines.append("# 本文件由 compile_rules.py 从 SOP 的 agent_rules 生成，手改会在下次编译时被覆盖。\n")
    lines.append("# 每条规则带唯一 ID，可在代码评审与审计中直接引用；机器可读版见 07-Agent-Rules/generated/。\n")
    for index, (domain, rules) in enumerate(rules_by_domain.items(), 1):
        lines.append(f"\n## {index}. {domain} — {DOMAIN_TITLES[domain]}（{len(rules)} 条）\n")
        for rule in sorted_rules(rules):
            suffix = "" if rule["overridable"] else " · 不可覆盖"
            lines.append(
                f"- [{rule['id']}] [{rule['enforcement'].upper()}]{suffix} "
                f"{rule['rule']} (Source: {rule['doc_id']}@v{rule['version']})\n"
            )
    return "".join(lines)


def expected_artifacts(rules_by_domain, stamp):
    """返回 {Path: bytes}，供写入与漂移比对共用。"""
    total = sum(len(rules) for rules in rules_by_domain.values())
    artifacts = {}
    for domain, rules in rules_by_domain.items():
        artifacts[GENERATED_DIR / f"{domain}-rules.md"] = render_domain_file(domain, rules).encode("utf-8")
    artifacts[MANIFEST_PATH] = render_manifest(rules_by_domain).encode("utf-8")
    artifacts[CURSORRULES_PATH] = render_cursorrules(rules_by_domain, total, stamp).encode("utf-8")
    return artifacts


def write_all(rules_by_domain, stamp):
    if GENERATED_DIR.exists():
        shutil.rmtree(GENERATED_DIR)
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)

    artifacts = expected_artifacts(rules_by_domain, stamp)
    for path, data in artifacts.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        label = "Generated" if path.suffix != ".json" else "Generated"
        print(f"[OK] {label}: {path} ({len(data)} bytes)")

    return sum(len(rules) for rules in rules_by_domain.values())


def main():
    parser = argparse.ArgumentParser(description="Knowledge-OS Rule Compiler")
    parser.add_argument("--dry-run", action="store_true", help="只校验 frontmatter，不写文件")
    args = parser.parse_args()

    rules_by_domain, errors, warnings, stamp = collect_rules()

    for warning in warnings:
        print(f"[WARN] {warning}")

    if errors:
        print("\n[ERROR] 规则编译失败（fail-closed，未写入任何文件）:")
        for error in errors:
            print(f"  - {error}")
        print("\n修复 SOP frontmatter 后重跑。\n")
        return 1

    total = sum(len(rules) for rules in rules_by_domain.values())

    if args.dry_run:
        print(f"\n[DRY RUN] 校验通过：{total} 条规则 / {len(rules_by_domain)} 域。未写入文件。\n")
        return 0

    write_all(rules_by_domain, stamp)
    print(f"\nRule Compilation Succeeded! Total Rules: {total}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
